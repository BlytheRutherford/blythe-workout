/**
 * Generates supabase/seed.sql from lib/engine/program.ts.
 *   node --experimental-strip-types scripts/gen-seed.ts
 */
import { writeFileSync } from "node:fs";
import { EXERCISES } from "../lib/engine/program";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);

const rows = EXERCISES.map(
  (e) =>
    `  (${q(e.slug)}, ${q(e.key)}, ${q(e.name)}, ${e.slotDay}, ${e.orderIndex}, ${e.restSeconds}, ${e.rangeMin}, ${e.rangeMax}, ${e.isUnilateral}, ${e.isBodyweight}, ${q(e.category)}, ${e.seedWeight}, ${e.seedReps}, ${q(e.variantRule ?? null)}, ${q(e.repUnit ?? null)})`,
);

const sql = `-- GENERATED by scripts/gen-seed.ts from lib/engine/program.ts. Do not edit by hand.
insert into public.exercises
  (slug, exercise_key, name, slot_day, order_index, rest_seconds, range_min, range_max, is_unilateral, is_bodyweight, category, seed_weight, seed_reps, variant_rule, rep_unit)
values
${rows.join(",\n")}
on conflict (slug) do update set
  exercise_key = excluded.exercise_key,
  name = excluded.name,
  slot_day = excluded.slot_day,
  order_index = excluded.order_index,
  rest_seconds = excluded.rest_seconds,
  range_min = excluded.range_min,
  range_max = excluded.range_max,
  is_unilateral = excluded.is_unilateral,
  is_bodyweight = excluded.is_bodyweight,
  category = excluded.category,
  seed_weight = excluded.seed_weight,
  seed_reps = excluded.seed_reps,
  variant_rule = excluded.variant_rule,
  rep_unit = excluded.rep_unit;

-- Remove slots that no longer exist in the program.
delete from public.exercises where slug not in (${EXERCISES.map((e) => q(e.slug)).join(", ")});
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql (${EXERCISES.length} exercises)`);
